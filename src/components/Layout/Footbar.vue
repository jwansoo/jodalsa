## 제8조 (회원탈퇴 및 자격 상실)

1. 회원은 언제든지 회사에 탈퇴를 요청할 수 있으며, 회사는 즉시 회원탈퇴를 처리합니다. 다만, 수강 중인 교육과정이 있는 경우 제4장의 환불 절차가 완료된 후 처리됩니다.
2. 회원이 다음 각 호의 사유에 해당하는 경우 회사는 회원자격을 제한·정지시킬 수 있습니다.
   1. 가입 신청 시 허위 내용을 등록한 경우
   2. 다른 사람의 서비스 이용을 방해하거나 그 정보를 도용하는 등 전자상거래 질서를 위협하는 경우
   3. 서비스를 이용하여 법령 또는 이 약관이 금지하는 행위를 하는 경우
   4. 제23조의 저작권 침해 행위를 한 경우
3. 회사가 회원자격을 제한·정지시킨 후 동일한 행위가 2회 이상 반복되거나 30일 이내에 그 사유가 시정되지 않는 경우 회사는 회원자격을 상실시킬 수 있습니다.
4. 회사가 회원자격을 상실시키는 경우에는 회원등록을 말소하며, 이 경우 회원에게 이를 통지하고 회원등록 말소 전에 소명할 기회를 부여합니다.

