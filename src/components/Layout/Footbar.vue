## 제28조 (재판권 및 준거법)

1. 회사와 이용자 간에 발생한 분쟁에 관한 소송은 제소 당시의 이용자의 주소에 의하고, 주소가 없는 경우에는 거소를 관할하는 지방법원의 전속관할로 합니다. 다만, 제소 당시 이용자의 주소 또는 거소가 분명하지 않거나 외국 거주자의 경우에는 「민사소송법」상의 관할법원에 제기합니다.
2. 회사와 이용자 간에 제기된 소송에는 대한민국 법을 적용합니다.

