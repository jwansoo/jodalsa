# 제4장 청약철회 및 환불

## 제15조 (청약철회)

1. 회사와 서비스 이용계약을 체결한 이용자는 「전자상거래법」 제17조제1항에 따라 계약내용에 관한 서면(전자문서 포함)을 받은 날부터 **7일 이내**에 청약을 철회할 수 있습니다. 다만, 서면을 받은 때보다 서비스 제공이 늦게 이루어진 경우에는 서비스를 제공받거나 제공이 시작된 날부터 7일 이내에 청약을 철회할 수 있습니다.
2. 「전자상거래법」 제17조제2항에 따라 다음 각 호의 경우에는 청약철회가 제한됩니다.
   1. 이용자의 책임 있는 사유로 재화 등이 멸실되거나 훼손된 경우
   2. 이용자의 사용 또는 일부 소비에 의하여 재화 등의 가치가 현저히 감소한 경우
   3. **디지털콘텐츠의 제공이 개시된 경우.** 다만, 가분적 디지털콘텐츠로 구성된 계약의 경우 제공이 개시되지 아니한 부분에 대하여는 최초열람시점에 청약철회가 가능합니다.
3. 회사는 제2항제2호부터 제4호까지의 사유로 청약철회가 제한되는 경우, 그 사실을 재화 등의 포장이나 그 밖에 이용자가 쉽게 알 수 있는 곳에 명확하게 표시하거나, 시험 사용 상품(맛보기 강의 등)을 제공하는 등의 조치를 취합니다. 이러한 조치를 취하지 아니한 경우에는 청약철회가 제한되지 않습니다.
4. 제1항 및 제2항에도 불구하고 제공된 콘텐츠의 내용이 **표시·광고의 내용과 다르거나 계약내용과 다르게 이행된 경우**, 이용자는 해당 콘텐츠를 공급받은 날부터 **3개월 이내**, 그 사실을 안 날 또는 알 수 있었던 날부터 **30일 이내**에 청약철회를 할 수 있습니다.
5. 청약철회는 사이트 내 신청 메뉴, 전자우편, 전화, 서면 등의 방법으로 할 수 있으며, 그 의사표시가 회사에 도달한 때에 효력이 발생합니다.

## 제16조 (청약철회의 효과)

1. 회사는 이용자로부터 청약철회의 의사표시를 받은 날부터 **3영업일 이내**에 이미 지급받은 대금을 환급합니다.
2. 회사가 제1항의 기간을 초과하여 환급을 지연한 경우, 그 지연기간에 대하여 「전자상거래법 시행령」이 정하는 지연이자율(**연 15%**)을 곱하여 산정한 지연배상금을 지급합니다.
3. 회사는 대금을 환급함에 있어서 이용자가 신용카드 또는 그 밖에 「전자상거래법 시행령」으로 정하는 결제수단으로 대금을 지급한 경우에는 지체 없이 해당 결제수단을 제공한 사업자로 하여금 대금의 청구를 정지하거나 취소하도록 요청합니다.
4. 청약철회의 경우 재화 등의 반환에 필요한 비용은 회사가 부담합니다. 다만, 제15조제2항에 따른 이용자의 귀책사유가 있는 경우에는 그러하지 아니합니다.
5. 이용자가 교재 등 유체물을 함께 제공받은 경우, 청약철회 시 해당 유체물을 반환하여야 하며, 반환이 불가능하거나 훼손된 경우에는 그 상당액을 공제할 수 있습니다.

## 제17조 (중도해지 및 환불기준)

1. 이용자는 제15조의 청약철회 기간이 경과한 후에도 언제든지 계약을 해지하고 잔여 수강기간에 대한 환불을 요청할 수 있습니다.
2. 환불금액은 다음 각 호의 기준에 따라 산정하며, 회사는 이용자에게 **유리한 기준**을 적용합니다.

### [기준 A] 이용일수 기준 (기간제 수강권)

| 구분 | 환불 금액 |
|---|---|
| 수강 시작 전 | 결제금액 전액 |
| 총 수강기간의 1/3 경과 전 | 결제금액의 2/3 해당액 |
| 총 수강기간의 1/2 경과 전 | 결제금액의 1/2 해당액 |
| 총 수강기간의 1/2 경과 후 | 환불하지 않음 |

### [기준 B] 진도율 기준 (강의 단위 수강권)

| 구분 | 환불 금액 |
|---|---|
| 수강 시작 전 | 결제금액 전액 |
| 열람페이지 수 1/3 미만 | 결제금액의 2/3 해당액 |
| 열람페이지 수 1/2 미만 | 결제금액의 1/2 해당액 |
| 열람페이지 수 1/2 이상 | 환불하지 않음 |

3. 총 수강기간이 1개월 이내인 단기 과정의 경우 제2항의 [기준 A]를 적용합니다.
4. 정기결제(구독형) 서비스의 경우, 해지 신청 시점의 결제주기에 대해서는 제2항을 적용하고, 다음 결제주기부터는 결제가 이루어지지 않습니다.
5. 할인·사은품·부가서비스가 제공된 상품의 경우, 이용자는 해당 사은품을 반환하거나 그 상당액을 공제한 후 환불받습니다. 다만, 사은품의 가액이 과다하여 실질적으로 환불을 제한하는 결과가 되어서는 안 됩니다.
6. 회사는 환불 신청을 받은 날부터 **3영업일 이내**에 환불을 처리합니다.

## 제18조 (회사의 귀책사유에 따른 환불)

1. 다음 각 호의 경우 이용자는 잔여 수강기간에 상응하는 금액의 전액 환불을 요청할 수 있으며, 회사는 이에 응하여야 합니다.
   1. 회사의 귀책사유로 서비스 제공이 불가능하게 된 경우
   2. 콘텐츠의 내용이 표시·광고와 현저히 다른 경우
   3. 회사가 사전 고지 없이 교육과정의 내용, 강사, 커리큘럼을 중대하게 변경한 경우
   4. 회사의 기술적 결함으로 정상적인 수강이 지속적으로 불가능한 경우
2. 제1항의 경우 회사는 이용자에게 발생한 손해를 배상합니다.

## 제19조 (환불의 제한)

이용자가 다음 각 호에 해당하는 행위를 한 경우, 회사는 이용계약을 해지하고 환불을 거절할 수 있습니다.

1. 제23조를 위반하여 콘텐츠를 무단 복제·녹화·배포·전송한 경우
2. 계정을 타인에게 양도·대여하거나 공유한 경우
3. 비정상적인 방법으로 진도율을 조작하거나 서비스 시스템을 침해한 경우

