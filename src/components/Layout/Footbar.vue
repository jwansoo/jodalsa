# 제6장 분쟁의 해결

## 제27조 (분쟁의 해결)

1. 회사는 이용자가 제기하는 정당한 의견이나 불만을 반영하고 그 피해를 보상처리하기 위하여 피해보상처리기구를 설치·운영할수 있습니다.
2. 회사는 이용자로부터 제출되는 불만사항 및 의견을 우선적으로 처리하며, 신속한 처리가 곤란한 경우에는 그 사유와 처리일정을 즉시 통보합니다.
3. 회사와 이용자 간에 발생한 분쟁에 관하여는 **공정거래위원회 고시 「소비자분쟁해결기준」**을 참조하여 해결합니다.
4. 회사와 이용자 간에 발생한 전자상거래 분쟁과 관련하여 이용자의 피해구제신청이 있는 경우에는 공정거래위원회 또는 시·도지사가 의뢰하는 분쟁조정기관, 한국소비자원 소비자분쟁조정위원회, 콘텐츠분쟁조정위원회, 전자거래분쟁조정위원회의 조정에 따를 수 있습니다.

