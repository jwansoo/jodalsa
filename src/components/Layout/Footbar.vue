# 제5장 의무와 책임

## 제20조 (회사의 의무)

1. 회사는 법령과 이 약관이 금지하거나 미풍양속에 반하는 행위를 하지 않으며, 계속적이고 안정적으로 서비스를 제공하기 위하여 최선을 다합니다.
2. 회사는 이용자가 안전하게 서비스를 이용할 수 있도록 개인정보 보호를 위한 보안시스템을 갖추어야 하며, 개인정보처리방침을 공시하고 준수합니다.
3. 회사는 이용자가 제기하는 의견이나 불만이 정당하다고 인정할 경우에는 이를 지체 없이 처리하여야 하며, 즉시 처리가 곤란한 경우에는 그 사유와 처리일정을 이용자에게 통보합니다.
4. 회사는 서비스와 관련한 이용자의 불만사항 및 분쟁을 처리하기 위한 인력 및 설비를 갖춥니다.

## 제21조 (개인정보의 보호)

1. 회사는 이용자의 개인정보 수집 시 서비스 제공에 필요한 최소한의 정보를 수집합니다.
2. 회사는 회원가입 시 계약 이행에 필요한 정보를 미리 수집하지 않습니다. 다만, 관련 법령상 의무이행을 위하여 구매계약 이전에 본인확인이 필요한 경우로서 최소한의 특정 개인정보를 수집하는 경우에는 그러하지 아니합니다.
3. 회사는 이용자의 개인정보를 수집·이용하는 때에는 당해 이용자에게 그 목적을 고지하고 동의를 받습니다.
4. 회사는 수집된 개인정보를 목적 외의 용도로 이용할 수 없으며, 새로운 이용목적이 발생한 경우 또는 제3자에게 제공하는 경우에는 이용·제공 단계에서 당해 이용자에게 그 목적을 고지하고 동의를 받습니다.
5. 개인정보의 처리에 관한 구체적인 사항은 회사가 별도로 정하여 게시하는 **개인정보처리방침**에 따릅니다.

## 제22조 (이용자의 의무)

이용자는 다음 각 호의 행위를 하여서는 안 됩니다.

1. 신청 또는 변경 시 허위 내용의 등록
2. 타인의 정보 도용
3. 회사가 게시한 정보의 변경
4. 회사가 정한 정보 이외의 정보(컴퓨터 프로그램 등)의 송신 또는 게시
5. 회사 및 제3자의 저작권 등 지식재산권에 대한 침해
6. 회사 및 제3자의 명예를 손상시키거나 업무를 방해하는 행위
7. 외설 또는 폭력적인 메시지·화상·음성 등 공서양속에 반하는 정보를 서비스에 공개 또는 게시하는 행위
8. 자동화 프로그램 등을 이용하여 서비스 시스템에 부하를 일으키는 행위

## 제23조 (저작권 및 콘텐츠 이용 제한)

1. 회사가 제공하는 모든 강의 콘텐츠, 학습자료, 문제, 이미지, 디자인, 상표 등에 대한 저작권 및 지식재산권은 회사 또는 정당한 권리자에게 귀속됩니다.
2. 이용자는 서비스를 이용함으로써 얻은 정보 중 회사 또는 제3자에게 지식재산권이 귀속된 정보를 회사의 사전 승낙 없이 복제, 녹화, 캡처, 송신, 출판, 배포, 방송, 2차적 저작물 작성 등의 방법으로 영리 또는 비영리 목적으로 이용하거나 제3자에게 이용하게 하여서는 안 됩니다.
3. 회사는 제2항의 위반행위를 방지하기 위하여 DRM 등 기술적 보호조치를 적용할 수 있으며, 이용자는 이를 우회·무력화하여서는 안 됩니다.
4. 이용자가 제2항 및 제3항을 위반한 경우, 회사는 즉시 서비스 이용을 정지하고 계약을 해지할 수 있으며, 「저작권법」에 따른 민·형사상 책임을 물을 수 있습니다.
5. 이용자가 서비스 내에 게시한 게시물의 저작권은 해당 이용자에게 귀속됩니다. 다만, 회사는 서비스의 운영·전시·홍보를 위하여 필요한 범위 내에서 이를 무상으로 사용할 수 있습니다.

## 제24조 (게시물의 관리)

1. 회사는 이용자가 게시한 게시물이 다음 각 호에 해당하는 경우 사전 통지 없이 삭제하거나 이동 또는 등록을 거부할 수 있습니다.
   1. 타인을 비방하거나 명예를 훼손하는 내용
   2. 공공질서 및 미풍양속에 위반되는 내용
   3. 범죄적 행위에 결부된다고 인정되는 내용
   4. 회사 또는 제3자의 지식재산권을 침해하는 내용
   5. 영리 목적의 광고성 게시물
   6. 기타 관계 법령 및 회사의 운영정책에 위반되는 경우
2. 권리침해를 주장하는 자의 요청이 있는 경우 회사는 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」에 따라 해당 게시물에 대한 접근을 임시적으로 차단할 수 있습니다.

## 제25조 (면책조항)

1. 회사는 천재지변, 전쟁, 기간통신사업자의 서비스 중지 등 불가항력으로 인하여 서비스를 제공할 수 없는 경우에는 서비스 제공에 관한 책임이 면제됩니다.
2. 회사는 이용자의 귀책사유(단말기·통신환경의 결함, 계정정보 관리 소홀 등)로 인한 서비스 이용 장애에 대하여 책임을 지지 않습니다.
3. 회사는 이용자가 서비스를 이용하여 기대하는 학습 성과나 시험 합격 등의 결과를 보장하지 않습니다. 다만, 회사가 광고 등을 통해 특정 결과를 명시적으로 보장한 경우에는 그러하지 아니합니다.
4. 회사는 이용자 상호 간 또는 이용자와 제3자 간에 서비스를 매개로 발생한 분쟁에 대하여 개입할 의무가 없으며, 이로 인한 손해를 배상할 책임이 없습니다.

## 제26조 (손해배상)

1. 회사 또는 이용자가 이 약관을 위반하여 상대방에게 손해를 발생시킨 경우 그 손해를 배상할 책임이 있습니다.
2. 회사의 고의 또는 중대한 과실로 인한 손해에 대하여는 회사의 책임을 제한하지 않습니다.

