# 제3장 서비스의 이용

## 제9조 (서비스의 내용)

1. 회사는 다음 각 호의 서비스를 제공할수있습니다.
   1. 온라인 동영상 강의 및 부속 학습자료의 제공
   2. 학습 진도관리 및 성취도 평가
   3. 온라인 질의응답, 학습 상담
   4. 수료증·이수증 발급(해당 과정에 한함)
   5. 기타 회사가 정하는 교육 관련 서비스
2. 회사는 개별 교육과정에 대하여 다음 사항을 사전에 사이트에 표시합니다.
   1. 교육과정명, 강사, 총 강의 수 및 총 재생시간
   2. 수강기간 및 수강기간 연장 조건
   3. 수강료 및 결제방법
   4. 교재 제공 여부 및 별도 비용
   5. 청약철회 및 환불의 조건·절차
   6. 최소 시스템 사양(권장 운영체제, 브라우저, 네트워크 환경 등)

## 제10조 (수강신청 및 계약의 성립)

1. 이용자는 사이트에서 다음 또는 이와 유사한 방법에 의하여 수강을 신청합니다.
   1. 교육과정 및 이용조건의 확인
   2. 결제수단의 선택 및 결제정보의 입력
   3. 이 약관에 동의하고 청약철회·환불조건 등에 관한 내용을 확인하였다는 표시
   4. 수강신청의 확인 및 회사에 대한 확인 요청
2. 계약은 회사가 이용자의 수강신청에 대하여 수신확인통지를 발송하고 그 통지가 이용자에게 도달한 때에 성립합니다.
3. 회사는 다음 각 호에 해당하는 신청에 대하여는 승낙하지 않을 수 있습니다.
   1. 신청 내용에 허위·기재누락·오기가 있는 경우
   2. 미성년자가 법정대리인의 동의 없이 신청한 경우
   3. 기타 승낙하는 것이 회사의 기술상 현저히 지장이 있다고 판단하는 경우

## 제11조 (대금의 지급방법)

1. 서비스 이용대금의 지급방법은 다음 각 호의 방법 중 이용자가 선택한 방법으로 할수 있습니다.
   1. 신용카드 결제(일시불 및 할부)
   2. 계좌이체, 무통장입금
   3. 실시간 계좌이체, 가상계좌
   4. 휴대전화 결제
   5. 간편결제(각종 페이) 및 상품권·포인트·마일리지 등
2. 이용자가 지급하는 금액에 대해서는 회사가 수취하는 대금 외에 어떠한 명목의 추가 비용도 청구하지 않습니다.
3. 결제 과정에서 발생하는 결제대행사의 정책 및 이용약관은 해당 결제대행사가 정하는 바에 따릅니다.

## 제12조 (수강기간)

1. 수강기간은 각 교육과정별로 사이트에 표시된 기간으로 하며, 별도의 표시가 없는 경우 결제일로부터 기산합니다.
2. 회사는 이용자의 신청에 따라 유상 또는 무상으로 수강기간을 연장할 수 있으며, 연장 조건은 각 교육과정별로 정하여 사전에 고지합니다.
3. 수강기간이 만료된 경우 해당 콘텐츠에 대한 이용 권한은 소멸하며, 이후에는 환불의 대상이 되지 않습니다.
4. 회사의 귀책사유로 서비스가 중단되어 이용자가 콘텐츠를 이용하지 못한 경우 회사는 그 중단 기간만큼 수강기간을 연장합니다.

## 제13조 (수강권의 양도 금지)

1. 수강권은 계약 당사자인 이용자 본인만 이용할 수 있으며, 이를 타인에게 양도·대여·판매하거나 담보로 제공할 수 없습니다.
2. 회사는 1개의 계정에 대하여 동시 접속 기기 수 및 접속 IP를 제한할 수 있으며, 계정 공유가 의심되는 경우 소명을 요구하거나 서비스 이용을 정지할 수 있습니다.

## 제14조 (서비스의 제공 및 중단)

1. 서비스는 연중무휴, 1일 24시간 제공함을 원칙으로 합니다.
2. 회사는 다음 각 호에 해당하는 경우 서비스의 전부 또는 일부를 제한하거나 중단할 수 있습니다.
   1. 컴퓨터 등 정보통신설비의 보수점검·교체 및 고장, 통신두절 등의 사유가 발생한 경우
   2. 정전, 제반 설비의 장애 또는 이용량 폭주 등으로 정상적인 서비스 이용에 지장이 있는 경우
   3. 기간통신사업자가 전기통신서비스를 중지한 경우
   4. 천재지변, 국가비상사태 등 불가항력적 사유가 있는 경우
3. 회사는 제2항의 사유로 서비스를 중단하는 경우 그 사유 및 기간을 사전에 공지합니다. 다만, 사전 공지가 불가능한 경우에는 사후에 지체 없이 공지합니다.
4. 회사가 사업종목의 전환, 사업의 포기, 업체 간의 통합 등의 이유로 서비스를 제공할 수 없게 되는 경우 회사는 **최소 30일 이전에** 이를 공지하고, 이용자에게 잔여 수강기간에 상응하는 대금을 환급합니다.

